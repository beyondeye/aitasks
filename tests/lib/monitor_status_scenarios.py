"""Synthetic monitor status scenarios → committed recording fixtures (t2034_3).

The committed fixture ``tests/fixtures/monitor_status/basic.jsonl`` is
SYNTHETIC: it is generated here, through the same ``StreamEncoder`` a status
server uses, from hand-built ``PaneSnapshot`` frames. It is deterministic (a
fixed clock and a fixed version string, so a release bump never changes it) and
``tests/test_monitor_status_recording.py`` regenerates it and requires the
result to be byte-identical to the committed file.

Pane content is prose-shaped, SGR-coloured text that names the state it stands
for. It deliberately reproduces NO dialog's line geometry (see "A verbatim
reproduction is indistinguishable" in
``aidocs/framework/monitor_idle_and_prompt_detection.md``); the recording tests
self-scan every content string against every prompt pattern.

Regenerate (only when the scenario or the wire format changes on purpose):

    python3 tests/lib/monitor_status_scenarios.py --write
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPTS = REPO_ROOT / ".aitask-scripts"
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

from monitor import status_protocol as sp  # noqa: E402
from monitor.monitor_core import (  # noqa: E402
    PaneCategory,
    PaneSnapshot,
    TmuxPaneInfo,
)

FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "monitor_status"
BASIC_FIXTURE = FIXTURE_DIR / "basic.jsonl"

#: 2026-01-01T00:00:00Z — a fixed wall clock so the fixture never drifts.
TS0 = 1767225600.0
TICK = 3.0
TICKS = 6
IDLE_THRESHOLD = 5.0
#: A fixed version string: the fixture must not change on a release bump.
FIXTURE_VERSION = "synthetic"
FIXTURE_SOURCE = "scenario:basic"
FIXTURE_NOTE = ("Synthetic fixture generated by tests/lib/monitor_status_scenarios.py "
                "through StreamEncoder; content is prose, not captured dialogs.")

ROOTS = {
    "aitasks": "/fixture/projects/aitasks",
    "aitasks_go": "/fixture/projects/aitasks_go",
}

GREEN, YELLOW, CYAN, DIM, RESET = "\x1b[32m", "\x1b[33m", "\x1b[36m", "\x1b[2m", "\x1b[0m"


def _pane(pane_id, session, window_index, window_name, *, command="claude",
          category=PaneCategory.AGENT, pane_index="0", history=None,
          shadow_target="", frozen_record="", record_id="", standin_ready="",
          width=200, height=50):
    return TmuxPaneInfo(
        window_index=window_index, window_name=window_name, pane_index=pane_index,
        pane_id=pane_id, pane_pid=41000 + int(pane_id[1:]), current_command=command,
        width=width, height=height, category=category, session_name=session,
        shadow_target=shadow_target, history_size=history,
        frozen_record=frozen_record, record_id=record_id or frozen_record,
        standin_ready=standin_ready,
    )


def _text(*lines: str) -> str:
    return "\n".join(lines) + "\n"


def _record(pane, ts, *, content, idle, awaiting="", agent_key="", scoped=None,
            compare_mode=sp.DEFAULT_COMPARE_MODE, compare_override=False,
            last_change=None):
    snap = PaneSnapshot(
        pane=pane, content=content, timestamp=0.0, idle_seconds=idle,
        is_idle=pane.category == PaneCategory.AGENT and idle > IDLE_THRESHOLD,
        awaiting_input=bool(awaiting), awaiting_input_kind=awaiting,
        agent_key=agent_key, scoped=bool(agent_key) if scoped is None else scoped,
    )
    return sp.pane_record(
        snap, compare_mode=compare_mode, compare_override=compare_override,
        last_change=ts - idle if last_change is None else last_change)


def _placeholder(pane, *, parked=False, frozen=False, last_change=None):
    snap = PaneSnapshot(
        pane=pane, content="", timestamp=0.0, idle_seconds=0.0, is_idle=False,
        awaiting_input=False, parked=parked, frozen=frozen,
        frozen_record_id=pane.frozen_record if frozen else "",
    )
    return sp.pane_record(snap, last_change=last_change)


def basic_frames() -> list[tuple[float, sp.StreamFrame]]:
    """The ``basic`` scenario: TICKS frames, 3 s apart.

    Covers two sessions; an active pane; an idle pane crossing the threshold
    (with a raw compare-mode override); awaiting panes of four kinds, one of
    them unscoped and one cleared mid-stream; completed panes (one from the
    start, one mid-stream); a shadow appearing at tick 2; a TUI pane and an
    OTHER pane; a parked placeholder with its global parked pair; a frozen
    stand-in; an agent removed and another appearing; a control-state blip;
    and the discovery changes all of that implies."""
    frames = []
    for tick in range(1, TICKS + 1):
        ts = TS0 + (tick - 1) * TICK
        age = (tick - 1) * TICK
        panes = {}

        # %1 — active claude agent: new output every tick.
        step = tick + 2
        p1 = _pane("%1", "aitasks", "1", "agent-pick-101", history=100 + 15 * tick)
        panes["%1"] = _record(p1, ts, agent_key="claude", idle=0.0, content=_text(
            f"{CYAN}fixture %1{RESET}: building module {step} of 9",
            f"{GREEN}ok{RESET} module {step - 1} finished (synthetic progress text)",
        ))

        # %2 — idle claude agent, raw compare-mode override; crosses the 5 s
        # threshold at tick 3.
        p2 = _pane("%2", "aitasks", "2", "agent-pick-102", history=80)
        panes["%2"] = _record(
            p2, ts, agent_key="claude", idle=2.0 + age, compare_mode="raw",
            compare_override=True,
            content=_text(f"{DIM}fixture %2: finished a step and is now quiet{RESET}"))

        # %3 — awaiting a plan approval (scoped to claude) the whole stream.
        p3 = _pane("%3", "aitasks", "3", "agent-pick-103", history=60)
        panes["%3"] = _record(
            p3, ts, agent_key="claude", awaiting="claude_plan_approval", idle=30.0 + age,
            content=_text(f"{YELLOW}fixture %3{RESET}: a plan approval is pending "
                          "(synthetic prose, not a dialog)"))

        # %4 — awaiting a question until tick 3; answered at tick 4 (active);
        # its task completes at tick 5.
        p4 = _pane("%4", "aitasks", "4", "agent-qa-104", history=40 + (10 * tick if tick >= 4 else 0))
        if tick <= 3:
            panes["%4"] = _record(
                p4, ts, agent_key="claude", awaiting="claude_askuserquestion",
                idle=12.0 + age,
                content=_text(f"{YELLOW}fixture %4{RESET}: a question to the user is "
                              "pending (synthetic prose, not a dialog)"))
        elif tick == 4:
            panes["%4"] = _record(p4, ts, agent_key="claude", idle=0.0, content=_text(
                f"{CYAN}fixture %4{RESET}: the answer arrived; writing tests"))
        else:
            panes["%4"] = _record(
                p4, ts, agent_key="claude", idle=(tick - 4) * TICK,
                last_change=TS0 + 3 * TICK,
                content=_text(f"{CYAN}fixture %4{RESET}: the answer arrived; writing tests"))

        # %5 — codex agent in the second session awaiting a permission (scoped).
        p5 = _pane("%5", "aitasks_go", "1", "agent-pick-16_2", command="codex", history=70)
        panes["%5"] = _record(
            p5, ts, agent_key="codex", awaiting="codex_permission", idle=20.0 + age,
            content=_text(f"{YELLOW}fixture %5{RESET}: a permission request is pending "
                          "(synthetic prose, not a dialog)"))

        # %6 — an agent whose command does not resolve (`node`): the kind comes
        # from the UNSCOPED list (scoped=false, agent_key="").
        p6 = _pane("%6", "aitasks_go", "2", "agent-pick-17", command="node", history=55)
        panes["%6"] = _record(
            p6, ts, agent_key="", scoped=False, awaiting="opencode_question",
            idle=9.0 + age,
            content=_text(f"{YELLOW}fixture %6{RESET}: a question is pending, detected "
                          "without a resolved agent (synthetic prose)"))

        # %7 — idle agent whose task is Done (completed); its window closes at tick 5.
        if tick <= 4:
            p7 = _pane("%7", "aitasks", "5", "agent-pick-99", history=200)
            panes["%7"] = _record(p7, ts, agent_key="claude", idle=300.0 + age, content=_text(
                f"{GREEN}fixture %7{RESET}: the task is archived; the agent has stopped"))

        # %8 — parked agent: the placeholder (no capture, no verdict).
        p8 = _pane("%8", "aitasks", "6", "agent-pick-105")
        panes["%8"] = _placeholder(p8, parked=True, last_change=TS0 - 600.0)

        # %9 — frozen stand-in viewer.
        p9 = _pane("%9", "aitasks", "7", "agent-pick-106", command="python3",
                   frozen_record="rec-fixture-106", standin_ready="rec-fixture-106")
        panes["%9"] = _placeholder(p9, frozen=True)

        # %10 — a TUI window; %11 — an OTHER window.
        p10 = _pane("%10", "aitasks", "0", "board", command="python3",
                    category=PaneCategory.TUI)
        panes["%10"] = _record(p10, ts, idle=age + 1.0, content=_text(
            f"{DIM}fixture %10: a board TUI pane (synthetic){RESET}"))
        p11 = _pane("%11", "aitasks_go", "0", "zsh", command="zsh",
                    category=PaneCategory.OTHER)
        panes["%11"] = _record(p11, ts, idle=age + 4.0, content=_text(
            "fixture %11: a plain shell window (synthetic)"))

        # %13 — a new agent appears at tick 4.
        if tick >= 4:
            p13 = _pane("%13", "aitasks", "8", "agent-pick-107", history=10 * tick)
            panes["%13"] = _record(p13, ts, agent_key="claude", idle=0.0, content=_text(
                f"{CYAN}fixture %13{RESET}: started, reading the task file (step {tick})"))

        # %12 — a shadow bound to %1, spawned at tick 2 (keyed by the FOLLOWED id).
        shadows = {}
        if tick >= 2:
            p12 = _pane("%12", "aitasks", "1", "agent-pick-101", pane_index="1",
                        shadow_target="%1", history=20 + tick)
            shadows["%1"] = _record(p12, ts, agent_key="claude", idle=0.0 if tick == 2 else TICK,
                                    content=_text(f"{DIM}fixture %12: shadow notes on %1, "
                                                  f"round {min(tick, 3)}{RESET}"))

        completed = {"%7"} if tick <= 4 else set()
        if tick >= 5:
            completed.add("%4")

        agents = [(r["pane"]["session_name"], r["pane"]["window_name"])
                  for r in panes.values() if r["pane"]["category"] == "agent"]
        windows = {}
        for rec in panes.values():
            p = rec["pane"]
            windows.setdefault((p["session_name"], p["window_name"]), []).append(
                (p["pane_id"], p["pane_pid"], False))
        if tick >= 2:
            windows[("aitasks", "agent-pick-101")].append(("%12", 41012, False))
        # A companion (minimonitor) helper pane: in discovery, never a snapshot.
        windows[("aitasks", "agent-pick-101")].append(("%14", 41014, False))

        frames.append((ts, sp.StreamFrame(
            panes=panes,
            shadows=shadows,
            completed=frozenset(completed),
            sessions=sp.sessions_member(ROOTS),
            parked=frozenset({("aitasks", "agent-pick-105")}),
            discovery=sp.discovery_member(ROOTS.keys(), agents, windows),
            control_state="reconnecting" if tick == 3 else "connected",
        )))
    return frames


def render_recording(frames, *, version=FIXTURE_VERSION, source=FIXTURE_SOURCE,
                     note=FIXTURE_NOTE) -> bytes:
    """Encode ``frames`` as a recording: the header, a welcome, the snapshot of
    the first frame (full content), then one delta per later frame."""
    encoder = sp.StreamEncoder()
    first_ts, first = frames[0]
    encoder.update(first, ts=first_ts)
    lines = [
        sp.encode({"type": "recording", "rev": sp.RECORDING_REV, "proto": sp.PROTO,
                   "version": version, "source": source, "created": first_ts,
                   "note": note}, direction=sp.RECORDING),
        sp.encode({"type": "welcome", "ts": first_ts, "proto": sp.PROTO,
                   "version": version, "server": {"impl": "scenario"}},
                  direction=sp.RECORDING),
        sp.encode(encoder.snapshot(ts=first_ts), direction=sp.RECORDING),
    ]
    for ts, frame in frames[1:]:
        lines.append(sp.encode(encoder.update(frame, ts=ts), direction=sp.RECORDING))
    return b"".join(lines)


def render_basic() -> bytes:
    return render_recording(basic_frames())


def write_fixture(path: Path = BASIC_FIXTURE) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(render_basic())
    return path


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true",
                        help=f"regenerate {BASIC_FIXTURE.relative_to(REPO_ROOT)}")
    args = parser.parse_args(argv)
    if args.write:
        print(f"wrote {write_fixture().relative_to(REPO_ROOT)}")
        return 0
    sys.stdout.buffer.write(render_basic())
    return 0


if __name__ == "__main__":
    sys.exit(main())
