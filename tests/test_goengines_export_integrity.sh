#!/usr/bin/env bash
# test_goengines_export_integrity.sh - .github/scripts/goengines_integrity.sh:
# the mode signal, legacy no-ops, and the export-mode checks over fixture
# goengines/ trees (t2138).
# Run: bash tests/test_goengines_export_integrity.sh
# Needs a Go toolchain and python3; without go it prints SKIP and passes.
#
# Fixtures are stdlib-only modules with local replaces, so no case reaches the
# network. The platform-only cases plant a file for the OS this host is not,
# and first prove the violation is invisible to a host-only go list.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
. "$PROJECT_DIR/tests/lib/scratch_cwd.sh"
enter_scratch_cwd

PASS=0
FAIL=0
TOTAL=0
. "$PROJECT_DIR/tests/lib/asserts.sh"
assert_counters_init

S="$PROJECT_DIR/.github/scripts/goengines_integrity.sh"

if ! command -v go >/dev/null 2>&1; then
    echo "SKIP: go not found on PATH"
    exit 0
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP" "$AIT_ASSERT_COUNTER_FILE"' EXIT

export GOTOOLCHAIN=local GOFLAGS='' GOWORK=off
unset GITHUB_OUTPUT GITHUB_ACTIONS || true

MOD=github.com/beyondeye/aitasks/goengines
SHA=0123456789abcdef0123456789abcdef01234567
GOVER="$(go env GOVERSION | sed -E 's/^go([0-9]+\.[0-9]+).*/\1/')"
HOST_OS="$(go env GOOS)"
if [[ "$HOST_OS" == darwin ]]; then OTHER_OS=linux; else OTHER_OS=darwin; fi

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    else
        shasum -a 256 "$1" | awk '{print $1}'
    fi
}

# record <dir>: (re)write EXPORT.txt from the tree's current files.
record() {
    local content p
    content="# aitasks_go export record (fixture)
format: 1
source: beyondeye/aitasks_go@$SHA
gate: go-test pass"
    while read -r p; do
        content+=$'\n'"file: $(sha256 "$1/$p") $p"
    done < <(find "$1" -type f ! -path "$1/.git/*" | sed "s|^$1/||" |
        grep -v -x -e README.md -e .gitignore -e EXPORT.txt | LC_ALL=C sort)
    printf '%s\n' "$content" >"$1/EXPORT.txt"
}

# mkfix <name>: a provenance-labelled, export-mode goengines/ tree; prints it.
mkfix() {
    local d="$TMP/$1/goengines"
    mkdir -p "$d/cmd/ait-testmap"
    cp "$PROJECT_DIR/goengines/build.sh" "$d/build.sh"
    printf 'module %s\n\ngo %s\n' "$MOD" "$GOVER" >"$d/go.mod"
    cat >"$d/cmd/ait-testmap/main.go" <<EOF
// Code generated by aitasks_go export from $SHA; DO NOT EDIT.

package main

import "fmt"

// SourceCommit names the private commit this tree was exported from.
const SourceCommit = "aitasks_go@$SHA"

func main() { fmt.Println(SourceCommit) }
EOF
    printf '/dist/\n' >"$d/.gitignore"
    printf '# goengines (fixture)\n' >"$d/README.md"
    git -C "$d" init -q
    record "$d"
    printf '%s\n' "$d"
}

# A package a fixture can import: <dir>/<rel> holding package <name>.
mkpkg() {
    mkdir -p "$1/$2"
    printf 'package %s\n\n// Name is a fixture symbol.\nfunc Name() string { return "%s" }\n' "$3" "$3" >"$1/$2/$3.go"
}

# A local module at <dir>/third_party/<name>, path example.com/<name>.
mklocalmod() {
    mkdir -p "$1/third_party/$2"
    printf 'module example.com/%s\n\ngo %s\n' "$2" "$GOVER" >"$1/third_party/$2/go.mod"
    printf 'package %s\n\n// Name is a fixture symbol.\nfunc Name() string { return "%s" }\n' "$2" "$2" >"$1/third_party/$2/$2.go"
}

run() { # run <verb> <dir> [env...] -> sets OUT, RC
    local verb="$1" d="$2"
    shift 2
    RC=0
    OUT="$(env "$@" bash "$S" "$verb" --dir "$d" 2>&1)" || RC=$?
}

# expect_refused <desc> <dir> <check> [detail substring]
expect_refused() {
    run check "$2"
    assert_eq "$1: check exits 1" "1" "$RC"
    assert_contains "$1: refused by $3" "INTEGRITY_FAIL:$3:" "$OUT"
    [[ -z "${4:-}" ]] || assert_contains "$1: the failure names $4" "$4" "$OUT"
    assert_not_contains "$1: no INTEGRITY_OK" "INTEGRITY_OK" "$OUT"
}

tree_sum() {
    (cd "$1" && find . -type f ! -path './.git/*' -exec cksum {} + | LC_ALL=C sort)
}

# --- 1. mode ---------------------------------------------------------------------
(
    d="$TMP/legacy/goengines"
    mkdir -p "$d"
    run mode "$d" GITHUB_OUTPUT="$TMP/legacy/out"
    assert_eq "no EXPORT.txt is legacy" "0|MODE:legacy" "$RC|$OUT"
    assert_eq "mode=legacy reaches GITHUB_OUTPUT" "mode=legacy" "$(cat "$TMP/legacy/out")"
    : >"$d/EXPORT.txt"
    run mode "$d" GITHUB_OUTPUT="$TMP/legacy/out2"
    assert_eq "an EXPORT.txt file is export" "0|MODE:export" "$RC|$OUT"
    assert_eq "mode=export reaches GITHUB_OUTPUT" "mode=export" "$(cat "$TMP/legacy/out2")"
    rm -f "$d/EXPORT.txt"
    mkdir "$d/EXPORT.txt"
    run mode "$d"
    assert_eq "an EXPORT.txt directory exits 1" "1" "$RC"
    assert_contains "… with MODE_ERROR" "MODE_ERROR:" "$OUT"
    rmdir "$d/EXPORT.txt"
    : >"$TMP/legacy/real"
    ln -s "$TMP/legacy/real" "$d/EXPORT.txt"
    run mode "$d"
    assert_eq "an EXPORT.txt symlink exits 1" "1" "$RC"
    assert_contains "… with MODE_ERROR" "MODE_ERROR:EXPORT.txt is a symlink" "$OUT"
    run check "$d"
    assert_eq "check refuses a symlinked record" "1" "$RC"
    run drift "$d"
    assert_eq "drift stays non-blocking on a symlinked record" "0" "$RC"
    assert_contains "… and reports it unchecked" "DRIFT_UNCHECKED:mode" "$OUT"
    run bogus "$d"
    assert_eq "an unknown verb is a usage error" "64" "$RC"
)

# --- 2. legacy check / drift never touch go --------------------------------------
(
    d="$TMP/legacy2/goengines"
    mkdir -p "$d" "$TMP/legacy2/bin"
    printf '#!/usr/bin/env bash\necho "$*" >>"%s"\nexit 1\n' "$TMP/legacy2/go.log" >"$TMP/legacy2/bin/go"
    chmod +x "$TMP/legacy2/bin/go"
    run check "$d" PATH="$TMP/legacy2/bin:$PATH"
    assert_eq "legacy check exits 0" "0" "$RC"
    assert_contains "legacy check reports legacy" "MODE:legacy" "$OUT"
    assert_contains "legacy check skips" "INTEGRITY_SKIPPED:legacy mode" "$OUT"
    run drift "$d" PATH="$TMP/legacy2/bin:$PATH"
    assert_eq "legacy drift" "0|DRIFT_SKIPPED:legacy" "$RC|$OUT"
    assert_file_not_exists "legacy mode never invokes go" "$TMP/legacy2/go.log"
)

# --- 3. a provenance-labelled export passes --------------------------------------
(
    d="$(mkfix ok)"
    before="$(tree_sum "$d")"
    run check "$d"
    assert_eq "the provenance-labelled fixture passes check" "0" "$RC"
    assert_contains "… MODE:export" "MODE:export" "$OUT"
    assert_contains "… INTEGRITY_OK (header, SourceCommit and EXPORT.txt are labels, not deps)" "INTEGRITY_OK" "$OUT"
    run drift "$d"
    assert_eq "an unchanged export has no drift" "0|DRIFT_NONE" "$RC|$OUT"
    assert_eq "check leaves the checkout untouched" "$before" "$(tree_sum "$d")"
    # A second shipped binary inside the allowlist is fine too.
    mkdir -p "$d/cmd/ait-monitord"
    printf 'package main\n\nfunc main() {}\n' >"$d/cmd/ait-monitord/main.go"
    run check "$d"
    assert_eq "an allowlisted ait-monitord passes" "0" "$RC"
)

# --- 4. private dependencies -----------------------------------------------------
(
    d="$(mkfix privimport)"
    mkdir -p "$d/internal/x"
    printf 'package x\n\nimport _ "github.com/beyondeye/aitasks_go/widget"\n' >"$d/internal/x/x.go"
    expect_refused "a private import" "$d" private-deps "imports github.com/beyondeye/aitasks_go/widget"

    d="$(mkfix privreplace)"
    mkdir -p "$d/priv"
    printf 'module github.com/beyondeye/aitasks_go\n\ngo %s\n' "$GOVER" >"$d/priv/go.mod"
    printf 'require github.com/beyondeye/aitasks_go v0.0.0\n\nreplace github.com/beyondeye/aitasks_go => ./priv\n' >>"$d/go.mod"
    expect_refused "a private require + replace" "$d" private-deps "go.mod requires github.com/beyondeye/aitasks_go"
    assert_contains "… the replace is named too" "go.mod replaces github.com/beyondeye/aitasks_go" "$OUT"

    d="$(mkfix outside)"
    printf 'require example.com/x v0.0.0\n\nreplace example.com/x => ../x\n' >>"$d/go.mod"
    expect_refused "a replace outside the tree" "$d" private-deps "outside the tree"

    d="$(mkfix absolute)"
    printf 'require example.com/x v0.0.0\n\nreplace example.com/x => /opt/x\n' >>"$d/go.mod"
    expect_refused "a replace to an absolute path" "$d" private-deps "absolute path"

    d="$(mkfix gosum)"
    printf 'github.com/beyondeye/aitasks_go v0.1.0 h1:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=\n' >"$d/go.sum"
    expect_refused "a private go.sum line" "$d" private-deps "go.sum lists github.com/beyondeye/aitasks_go"
)

# --- 5. platform-only violations (the matrix loop) -------------------------------
(
    d="$(mkfix platform_tui)"
    mkpkg "$d" tui/widget widget
    printf 'package main\n\nimport _ "%s/tui/widget"\n' "$MOD" >"$d/cmd/ait-testmap/dep_${OTHER_OS}.go"
    host="$(cd "$d" && go list -deps ./cmd/ait-testmap)"
    assert_not_contains "control: a host-only go list does not see the $OTHER_OS-only TUI import" "tui/widget" "$host"
    expect_refused "a $OTHER_OS-only TUI dependency" "$d" closure "${OTHER_OS}_"
    assert_contains "… naming the package" "$MOD/tui/widget is a TUI package" "$OUT"
    assert_not_contains "… and never a host target" "INTEGRITY_FAIL:closure:${HOST_OS}_" "$OUT"

    d="$(mkfix platform_priv)"
    mkdir -p "$d/internal/x"
    printf 'package x\n' >"$d/internal/x/x.go"
    printf 'package x\n\nimport _ "github.com/beyondeye/aitasks_go/widget"\n' >"$d/internal/x/x_${OTHER_OS}.go"
    host="$(cd "$d" && go list -e -deps -f '{{.ImportPath}}: {{join .Imports " "}}' ./...)"
    assert_not_contains "control: a host-only go list does not see the $OTHER_OS-only private import" "aitasks_go" "$host"
    expect_refused "a $OTHER_OS-only private import" "$d" private-deps "${OTHER_OS}_"
)

# --- 6. matrix, gofmt, independent build ------------------------------------------
(
    d="$(mkfix matrix)"
    grep -v '^readonly MATRIX=' "$PROJECT_DIR/goengines/build.sh" >"$d/build.sh"
    expect_refused "a build.sh without MATRIX" "$d" matrix

    d="$(mkfix gofmt)"
    printf 'package main\n\nvar  ugly = 1\n' >"$d/cmd/ait-testmap/ugly.go"
    expect_refused "an unformatted file" "$d" gofmt "cmd/ait-testmap/ugly.go"

    d="$(mkfix untidy)"
    mklocalmod "$d" unused
    printf 'require example.com/unused v0.0.0\n\nreplace example.com/unused => ./third_party/unused\n' >>"$d/go.mod"
    before="$(tree_sum "$d")"
    expect_refused "an untidy go.mod" "$d" independent-build "tidy"
    assert_eq "a failing check leaves the checkout untouched" "$before" "$(tree_sum "$d")"

    d="$(mkfix broken)"
    printf 'package main\n\nfunc broken() { undefinedSymbol() }\n' >"$d/cmd/ait-testmap/broken.go"
    expect_refused "a compile error" "$d" independent-build "go build"
)

# --- 7. per-binary closure --------------------------------------------------------
(
    d="$(mkfix tui)"
    mkpkg "$d" tui/widget widget
    printf 'package main\n\nimport _ "%s/tui/widget"\n' "$MOD" >"$d/cmd/ait-testmap/tui.go"
    expect_refused "a TUI package in the testmap closure" "$d" closure "ait-testmap:$MOD/tui/widget"

    d="$(mkfix charm)"
    mklocalmod "$d" charm
    printf 'require example.com/charm v0.0.0\n\nreplace example.com/charm => ./third_party/charm\n' >>"$d/go.mod"
    printf 'package main\n\nimport _ "example.com/charm"\n' >"$d/cmd/ait-testmap/charm.go"
    expect_refused "a non-allowlisted module in the testmap closure" "$d" closure "is from example.com/charm, not on the allowlist"

    d="$(mkfix monitord)"
    mkpkg "$d" tui/widget widget
    mkdir -p "$d/cmd/ait-monitord"
    printf 'package main\n\nimport _ "%s/tui/widget"\n\nfunc main() {}\n' "$MOD" >"$d/cmd/ait-monitord/main.go"
    expect_refused "a TUI package in the ait-monitord closure" "$d" closure "ait-monitord:$MOD/tui/widget"

    d="$(mkfix nocmd)"
    mv "$d/cmd/ait-testmap" "$d/cmd/other"
    expect_refused "no cmd/ait-testmap" "$d" closure "cmd/ait-testmap is missing"
)

# --- 8. malformed records ---------------------------------------------------------
(
    d="$(mkfix record)"
    good="$(cat "$d/EXPORT.txt")"
    h="$(sha256 "$d/build.sh")"
    bad_record() { # bad_record <desc> <content> <detail>
        printf '%s\n' "$2" >"$d/EXPORT.txt"
        expect_refused "$1" "$d" record "$3"
        run drift "$d"
        assert_eq "$1: drift stays non-blocking" "0" "$RC"
        assert_contains "$1: drift reports the record unchecked" "DRIFT_UNCHECKED:" "$OUT"
    }
    bad_record "format 2" "${good/format: 1/format: 2}" "unsupported format '2'"
    bad_record "a missing source" "$(printf '%s\n' "$good" | grep -v '^source:')" "exactly one 'source:'"
    bad_record "a short hash" "$good
file: ${h:1} extra.go" "<64 hex sha256> <path>"
    bad_record "a .. path" "$good
file: $h ../outside.go" "unsafe path '../outside.go'"
    bad_record "a duplicate path" "$good
file: $h build.sh" "duplicate path 'build.sh'"
    bad_record "the record listing itself" "$good
file: $h EXPORT.txt" "'EXPORT.txt' is never part of an export"
    bad_record "a public-maintained file" "$good
file: $h README.md" "'README.md' is never part of an export"
    # Unknown keys are tolerated: the exporter may add fields within format 1.
    printf '%s\nmanifest: sha256:%s\nfuture-key: anything\nremoved: old/file.go\n' "$good" "$h" >"$d/EXPORT.txt"
    run check "$d"
    assert_eq "unknown keys are tolerated" "0" "$RC"
)

# --- 9. drift ---------------------------------------------------------------------
(
    d="$(mkfix drift)"
    mkdir -p "$d/dist" "$d/internal/y"
    printf 'ignored\n' >"$d/dist/asset"
    printf 'package y\n' >"$d/internal/y/y.go"
    record "$d"
    printf '// an emergency fix\n' >>"$d/cmd/ait-testmap/main.go"
    rm "$d/internal/y/y.go"
    printf 'package main\n' >"$d/cmd/ait-testmap/added.go"
    run drift "$d"
    assert_eq "drift exits 0" "0" "$RC"
    assert_contains "a modified file" "DRIFT:modified:cmd/ait-testmap/main.go" "$OUT"
    assert_contains "a deleted file" "DRIFT:missing:internal/y/y.go" "$OUT"
    assert_contains "an added file" "DRIFT:unlisted:cmd/ait-testmap/added.go" "$OUT"
    assert_contains "three entries" "DRIFT_FOUND:3" "$OUT"
    assert_not_contains "gitignored files are not drift" "dist/asset" "$OUT"
    assert_not_contains "README.md is public-maintained" "README.md" "$OUT"
    assert_not_contains "no annotations outside Actions" "::warning" "$OUT"
    run drift "$d" GITHUB_ACTIONS=true
    assert_contains "Actions gets a warning annotation per entry" \
        "::warning file=goengines/cmd/ait-testmap/main.go,title=goengines drift::" "$OUT"
    assert_contains "… naming the emergency-fix protocol" "Emergency fixes" "$OUT"
)

# --- 9b. awkward file names are enumerated, with git and without -------------------
(
    d="$(mkfix names)"
    for n in 'with space.txt' 'odd "quote".txt' 'back\slash.txt' 'comma,colon:name.txt'; do
        printf 'x\n' >"$d/$n"
    done
    for how in git find; do
        [[ "$how" == find ]] && rm -rf "$d/.git"
        run drift "$d"
        assert_eq "$how: drift exits 0" "0" "$RC"
        assert_contains "$how: a name with a space" 'DRIFT:unlisted:with space.txt' "$OUT"
        assert_contains "$how: a name with a double quote" 'DRIFT:unlisted:odd "quote".txt' "$OUT"
        assert_contains "$how: a name with a backslash" 'DRIFT:unlisted:back\slash.txt' "$OUT"
        assert_contains "$how: four entries" "DRIFT_FOUND:4" "$OUT"
    done
    run drift "$d" GITHUB_ACTIONS=true
    assert_contains "annotation properties are escaped" \
        "::warning file=goengines/comma%2Ccolon%3Aname.txt,title=goengines drift::" "$OUT"
)

# --- 9b'. a name with a newline never matches two adjacent record paths -------------
(
    d="$(mkfix newline)"
    printf 'a\n' >"$d/alpha"
    printf 'b\n' >"$d/beta"
    record "$d"
    assert_eq "control: alpha and beta are adjacent record entries" "beta" \
        "$(grep -A1 ' alpha$' "$d/EXPORT.txt" | sed -n '2s/^file: [0-9a-f]* //p')"
    printf 'x\n' >"$d/alpha"$'\n'"beta"
    printf 'x\n' >"$d/other"$'\n'"name"
    for how in git find; do
        [[ "$how" == find ]] && rm -rf "$d/.git"
        run drift "$d"
        assert_contains "$how: alpha<newline>beta is unlisted" "DRIFT:unlisted:\$'alpha\\nbeta'" "$OUT"
        assert_contains "$how: other<newline>name is unlisted" "DRIFT:unlisted:\$'other\\nname'" "$OUT"
        assert_contains "$how: two entries" "DRIFT_FOUND:2" "$OUT"
    done
)

# --- 9c. unreadable input fails check and never blocks drift ----------------------
if [[ "$(id -u)" -ne 0 ]]; then
    (
        d="$(mkfix unreadable)"
        chmod 000 "$d/EXPORT.txt"
        run mode "$d"
        assert_eq "an unreadable record is still export mode" "0|MODE:export" "$RC|$OUT"
        expect_refused "an unreadable record" "$d" record "EXPORT.txt cannot be read"
        run drift "$d"
        assert_eq "an unreadable record: drift exits 0" "0" "$RC"
        assert_contains "… and reports it" "DRIFT_UNCHECKED:EXPORT.txt cannot be read" "$OUT"
        chmod 644 "$d/EXPORT.txt"
        chmod 000 "$d/build.sh"
        expect_refused "an unreadable exported file" "$d" copy
        run drift "$d"
        assert_eq "an unreadable exported file: drift exits 0" "0" "$RC"
        assert_contains "… and reports it" "DRIFT_UNCHECKED:cannot hash build.sh" "$OUT"
        chmod 644 "$d/build.sh"
    )
else
    echo "SKIP: unreadable-input cases (running as root)"
fi

# --- 9e. an inherited alternate modfile reaches no check --------------------------
# The real go.mod replaces an allowlisted module with an absolute path outside
# the tree; a benign go.mod offered through GOFLAGS=-modfile (directly, or from
# a go env file) must not be what the checks read.
(
    d="$(mkfix modfile)"
    benign="$TMP/modfile/benign.mod"
    cp "$d/go.mod" "$benign"
    printf 'require gopkg.in/yaml.v3 v3.0.1\n\nreplace gopkg.in/yaml.v3 => /opt/yaml\n' >>"$d/go.mod"
    expect_refused "an outside replace (control)" "$d" private-deps "absolute path"
    run check "$d" GOFLAGS="-modfile=$benign"
    assert_eq "GOFLAGS=-modfile does not hide the real go.mod" "1" "$RC"
    assert_contains "… still refused for the absolute replace" "INTEGRITY_FAIL:private-deps:go.mod replaces gopkg.in/yaml.v3 with the absolute path /opt/yaml" "$OUT"
    printf 'GOFLAGS=-modfile=%s\n' "$benign" >"$TMP/modfile/goenv"
    run check "$d" GOENV="$TMP/modfile/goenv"
    assert_eq "a go env file's -modfile does not hide the real go.mod" "1" "$RC"
    assert_contains "… still refused" "with the absolute path /opt/yaml" "$OUT"
)

# --- 9d. an inherited GOWORK reaches no check ------------------------------------
(
    d="$(mkfix gowork)"
    ws="$TMP/gowork/ws"
    mkdir -p "$ws/other"
    printf 'module example.com/other\n\ngo %s\n' "$GOVER" >"$ws/other/go.mod"
    printf 'go %s\n\nuse ./other\n' "$GOVER" >"$ws/go.work"
    run check "$d" GOWORK="$ws/go.work"
    assert_eq "an unrelated workspace in GOWORK does not change the verdict" "0" "$RC"
    assert_contains "… INTEGRITY_OK" "INTEGRITY_OK" "$OUT"
)

# --- 10. the allowlist restates guards_test.go ------------------------------------
GUARDS="$PROJECT_DIR/goengines/guards_test.go"
if [[ -f "$GUARDS" ]]; then
    want="$(sed -n '/^var allowedDeps = \[\]string{/,/^}/p' "$GUARDS" | grep -o '"[^"]*"' | tr -d '"' | LC_ALL=C sort)"
    got="$(sed -n '/^readonly CLOSURE_ALLOWED_MODULES=(/,/^)/p' "$S" | sed -n 's/^ *\([a-z][^ ]*\)$/\1/p' | LC_ALL=C sort)"
    assert_contains "guards_test.go allowedDeps parsed" "gopkg.in/yaml.v3" "$want"
    assert_eq "the closure allowlist equals guards_test.go allowedDeps" "$want" "$got"
else
    echo "SKIP: allowlist sync (goengines/guards_test.go is not in this tree)"
fi

# --- footer ---------------------------------------------------------------------
assert_counters_load
echo ""
echo "Results: $PASS passed, $FAIL failed, $TOTAL total"
[[ "$FAIL" -eq 0 ]] || exit 1
echo "ALL TESTS PASSED"
