"""Sum the per-repository realrepo reports of one directory (t1954_4): python3 tools/agg_realrepo.py results/t4 > results/t4/realrepo_totals.md."""
import collections
import glob
import sys

d = sys.argv[1]
tot = collections.defaultdict(lambda: [0] * 8)  # files unsup errors cls_files cls_lines rec_differ unc_base unc_subj
base = collections.defaultdict(lambda: [0, 0])
inputs = []
for f in sorted(glob.glob(d + "/realrepo_*.md")):
    sec = None
    for l in open(f):
        if l.startswith("Input:"):
            inputs.append(l.strip())
        if l.startswith("## "):
            sec = l[3:].strip()
            continue
        if not l.startswith("| ") or l.startswith(("| subject", "| lang", "|---")):
            continue
        c = [x.strip() for x in l.strip().strip("|").split("|")]
        if sec == "Files per language":
            base[c[0]][0] += int(c[1])
            if c[2] != "unsupported":
                base[c[0]][1] += int(c[2])
        elif sec == "Candidate vs baseline":
            cf, cl = [int(x) for x in c[5].split("/")]
            vals = [int(c[2]), int(c[3]), int(c[4]), cf, cl, int(c[6]), int(c[7]), int(c[8])]
            t = tot[(c[0], c[1])]
            for i, v in enumerate(vals):
                t[i] += v
print("# Real-repository disagreement: totals over the walked repositories (t1954_4)\n")
print("Generated by `python3 tools/agg_realrepo.py " + d + "`: the sum of every `realrepo_*.md` in that directory. Each walk read a temporary checkout of a recorded commit (`inputs.md`); counts and paths only, nothing executed. A subject is compared with the landed baseline on the files of its own languages.\n")
print("Inputs:\n")
for i in inputs:
    print("- " + i)
print("\n| lang | files | baseline uncertain |\n|---|---|---|")
for k in ["bash", "python", "go", "kotlin", "typescript", "tsx", "javascript", "java", "rust", "swift"]:
    if k in base:
        print(f"| {k} | {base[k][0]} | {base[k][1]} |")
print("\n| subject | lang | files | unsupported | provider errors | comment-class differs (files / lines) | records differ (files) | uncertain: baseline only | uncertain: subject only |\n|---|---|---|---|---|---|---|---|---|")
for (s, lang), t in sorted(tot.items()):
    print(f"| {s} | {lang} | {t[0]} | {t[1]} | {t[2]} | {t[3]} / {t[4]} | {t[5]} | {t[6]} | {t[7]} |")
