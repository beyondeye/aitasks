// pathGo lists every `go` on PATH except the toolchain this binary runs on
// (`go run` prepends the auto-switched toolchain's GOROOT/bin to PATH).
func pathGo() string {
	skip := filepath.Join(runtime.GOROOT(), "bin")
	var out []string
	seen := map[string]bool{}
	for _, d := range filepath.SplitList(os.Getenv("PATH")) {
		if d == skip || seen[d] {
			continue
		}
		seen[d] = true
		p := filepath.Join(d, "go")
		if st, err := os.Stat(p); err != nil || st.IsDir() {
			continue
		}
		c := exec.Command(p, "version")
		c.Env = append(os.Environ(), "GOTOOLCHAIN=local")
		o, err := c.Output()
		if err != nil {
			continue
		}
		out = append(out, p+": "+strings.TrimSpace(strings.TrimPrefix(string(o), "go version ")))
	}
	if len(out) == 0 {
		return "not available"
	}
	return strings.Join(out, "; ")
}

// cmdEnv records the measurement environment: date, host, tool and module
// versions, the toolchain actually selected, the RSS method and the PIN
// identity. A tool that is absent is written "not available", never guessed.
func cmdEnv(args []string) int {
	fs := flag.NewFlagSet("env", flag.ExitOnError)
	out := fs.String("out", "results/environment.md", "output file")
	t3 := fs.Bool("t3", false, "only (re)write the t1954_3 tools section of --out, keeping the rest of the file")
	_ = fs.Parse(args)
	sh := func(cmd string, env ...string) string {
		c := exec.Command("bash", "-c", cmd)
		c.Env = append(os.Environ(), env...)
		o, err := c.CombinedOutput()
		s := strings.TrimSpace(string(o))
		if err != nil || s == "" {
			return "not available"
		}
		if i := strings.IndexByte(s, '\n'); i >= 0 {
			s = s[:i]
		}
		return s
	}
	if *t3 {
		return envT3(*out, sh)
	}
	cpu := sh(`grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ //'`)
	rows := [][2]string{
		{"date (UTC)", time.Now().UTC().Format("2006-01-02")},
		{"host", runtime.GOOS + "/" + runtime.GOARCH + ", " + sh("uname -r")},
		{"CPU", cpu},
		{"nproc", sh("nproc")},
		{"go on PATH (outside the module's toolchain switch)", pathGo()},
		{"go (inside this module)", sh("go version")},
		{"go (selected for this module, GOTOOLCHAIN=" + sh("go env GOTOOLCHAIN") + ")", runtime.Version() + " (the harness binary's runtime)"},
		{"goengines module (snapshot)", "github.com/beyondeye/aitasks/goengines => ./.baseline/goengines (go.mod `go 1.26.0`, `toolchain go1.27.1`)"},
		{"mvdan.cc/sh/v3", sh("go list -m -f '{{.Version}}' mvdan.cc/sh/v3")},
		{"python3", sh("python3 --version")},
		{"node", sh("node --version")},
		{"typescript (oracle)", sh(`node -e 'console.log(require("typescript").version)'`, "NODE_PATH="+os.Getenv("T1954_TS_NODE_MODULES"))},
		{"bash", sh("bash --version")},
		{"rustc", sh("rustc --version")},
		{"javac", sh("javac -version")},
		{"kotlinc (T1954_KOTLINC, scratch download)", sh(`"$T1954_KOTLINC" -version 2>&1 | tail -1`)},
		{"swiftc (docker " + os.Getenv("T1954_SWIFT_DOCKER") + ")", sh(`docker run --rm "$T1954_SWIFT_DOCKER" swiftc --version 2>&1 | head -1`)},
		{"taskset", sh("taskset --version")},
		{"/usr/bin/time", sh("/usr/bin/time --version 2>&1")},
		{"peak-RSS method", "inside each measured process: `getrusage(RUSAGE_SELF)` for the process, `getrusage(RUSAGE_CHILDREN)` for its subprocesses — the latter an upper bound (a forked child's `ru_maxrss` includes pages shared at fork); KiB on Linux; `/usr/bin/time` is not installed here"},
		{"aitasks HEAD at measurement", sh("git -C " + id.Root + " rev-parse HEAD")},
		{"baseline identity", id.Header()},
	}
	var b strings.Builder
	b.WriteString("# Measurement environment (t1954_1)\n\nGenerated by `go run ./cmd/t1954 env`. Tool locations for the native oracles: `T1954_TS_NODE_MODULES` (the `typescript` npm package installed into a scratch dir), `T1954_KOTLINC` (the kotlinc release zip unpacked into a scratch dir, run on the local JDK), `T1954_SWIFT_DOCKER` (the official `swift` image). Nothing is installed system-wide.\n\n| item | value |\n|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s |\n", r[0], esc(r[1]))
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fail(1, err)
	}
	fmt.Printf("WROTE:%s\n", *out)
	return 0
}

const t3Section = "## t1954_3 tools"

// envT3 replaces only the t1954_3 section: every tool the t1954_3 providers
// and experiments use, installed into a scratch dir (never system-wide) and
// named by an environment variable. A tool that is absent is written "not
// available", never guessed.
func envT3(out string, sh func(string, ...string) string) int {
	old, _ := os.ReadFile(out)
	keep := string(old)
	if i := strings.Index(keep, "\n"+t3Section); i >= 0 {
		keep = keep[:i+1]
	}
	rows := [][2]string{
		{"date (UTC)", time.Now().UTC().Format("2006-01-02")},
		{"chroma (Go module)", sh("go list -m -f '{{.Version}}' github.com/alecthomas/chroma/v2")},
		{"antlr4-go runtime (Go module)", sh("go list -m -f '{{.Version}}' github.com/antlr4-go/antlr/v4")},
		{"ANTLR tool + grammars-v4 (antlr/LOCK)", sh("grep -E '^(tool|grammars_v4):' antlr/LOCK | tr '\\n' ' '")},
		{"Pygments (T1954_PYGMENTS_PYTHON)", sh(`"$T1954_PYGMENTS_PYTHON" -c 'import pygments, sys; print("pygments", pygments.__version__, "on python", sys.version.split()[0])'`)},
		{"typescript (T1954_TS_NODE_MODULES, tsnative)", sh(`node -e 'console.log(require("typescript").version)'`, "NODE_PATH="+os.Getenv("T1954_TS_NODE_MODULES"))},
		{"kotlinc / compiler PSI (T1954_KOTLINC, ktpsi)", sh(`"$T1954_KOTLINC" -version 2>&1 | tail -1`)},
		{"vscode-textmate / oniguruma / tm-grammars (T1954_TM_NODE_MODULES)", sh(`echo '{"version":true}' | NODE_PATH="$T1954_TM_NODE_MODULES" node oracle/textmate_oracle.js`)},
		{"gopls (T1954_GOPLS)", sh(`"$T1954_GOPLS" version | head -1`)},
		{"pyright (T1954_LSP_NODE_MODULES)", sh(`node -e 'console.log(require("pyright/package.json").version)'`, "NODE_PATH="+os.Getenv("T1954_LSP_NODE_MODULES"))},
		{"typescript-language-server (T1954_LSP_NODE_MODULES)", sh(`node -e 'console.log(require("typescript-language-server/package.json").version)'`, "NODE_PATH="+os.Getenv("T1954_LSP_NODE_MODULES"))},
		{"kotlin-lsp (T1954_KOTLIN_LSP)", sh(`cat "$(dirname "$T1954_KOTLIN_LSP")/build.txt"`)},
		{"scc (T1954_SCC)", sh(`"$T1954_SCC" --version`)},
		{"java (host)", sh("java -version 2>&1 | head -1")},
		{"node (host)", sh("node --version")},
		{"zig (T1954_ZIG, tswasm rebuild)", sh(`"$T1954_ZIG" version`)},
		{"tree-sitter CLI (host)", sh("tree-sitter --version")},
	}
	var b strings.Builder
	b.WriteString(keep)
	if !strings.HasSuffix(keep, "\n") && keep != "" {
		b.WriteString("\n")
	}
	b.WriteString("\n" + t3Section + "\n\nGenerated by `go run ./cmd/t1954 env --t3` (the section above is t1954_1's and is kept). Every tool was installed into a scratch dir and smoke-called before any provider code (pre-phase `toolchain_fetch_smoke`); sources: the Go module proxy, PyPI (`pip install pygments==2.21.0` into a venv), npm (`pyright@1.1.414 typescript-language-server@6.0.2 typescript@5.9.3 vscode-textmate@9.3.2 vscode-oniguruma tm-grammars`), `go install golang.org/x/tools/gopls@latest` and `github.com/boyter/scc/v4@v4.1.0`, the kotlinc 2.4.21 release zip, the kotlin-lsp standalone archive (`download.jetbrains.com/language-server/kotlin-server/263.6379.0/kotlin-server-263.6379.0.tar.gz`, sha256 `ab8ca4455dc2fc5fe1a24db2bccc46c104254d2c465155c4251ee65df8f3f7cc`, checked against JetBrains' published checksum), the ANTLR jar (sha256 in `antlr/LOCK`) and the zig 0.17.0 release tarball.\n\n| item | value |\n|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s |\n", r[0], esc(r[1]))
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fail(1, err)
	}
	fmt.Printf("WROTE:%s\n", out)
	return 0
}
