package main

import (
	"encoding/json"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/beyondeye/aitasks/goengines/internal/testmap/registry"
)

// [characterize_scan_check_without_scoped] The behaviour of `scan` and `check`
// on a registry that uses no scoped key, pinned byte for byte as M2.1 shipped
// it, before M2.5 extended both verbs. A repository without broad tests must
// see exactly what it saw before: the same lines, exit codes and
// `_scanned.yaml`, and no `_scoped.yaml`. Only the `--json` objects may grow,
// and only by the keys named in jsonAdditions. (M2.6 deliberately adds its two
// summary lines, emptyAdoption, to every `check` and `summary` to its JSON.)

// jsonAdditions are the keys M2.5 adds to `scan --json`.
var jsonAdditions = map[string]bool{"scoped": true, "reads": true, "drift": true}

const characterizedScanned = "# Generated by ait-testmap scan --apply. Do not edit: re-run the scan.\n" +
	"contract: 1\nunits:\n  - test: app/F.kt#Welcome\n    line: 4\n    variants: [ltr, rtl]\n    covers:\n" +
	"      - source: src/b.kt\n        line: 5\n  - test: tests/test_a.sh\n    covers:\n" +
	"      - source: src/a.sh\n        line: 2\n        stamped_at: \"2026-10-01\"\n        stamped_blob: \"0123456789\"\n"

func TestCharacterizeScanCheckWithoutScoped(t *testing.T) {
	root := repo(t)
	write(t, root, map[string]string{registry.RegistryDir + "/x.yaml": "contract: 1\nowns: [\"src/**\"]\nedges: [{test: tests/test_a.sh, covers: src/b.kt}]\n"})
	withInputs(t, fakes())
	steps := []struct {
		args     []string
		code     int
		out      string
		jsonKeys map[string]any // compared instead of out when set
	}{
		{args: []string{"scan"}, out: "SCAN:2|2|2\nSCAN_DRIFT:aitestmap/registry/_scanned.yaml\n"},
		{args: []string{"scan", "--json"}, jsonKeys: map[string]any{"units": 2.0, "edges": 2.0, "variants": 2.0, "changed": true, "wrote": []any{}, "findings": nil}},
		{args: []string{"check"}, out: "SCAN_DRIFT:aitestmap/registry/_scanned.yaml\n" + emptyAdoption + "CHECK:pass|1|0\n"},
		{args: []string{"scan", "--apply"}, out: "SCAN:2|2|2\nWROTE:aitestmap/registry/_scanned.yaml\n"},
		{args: []string{"scan"}, out: "SCAN:2|2|2\n"},
		{args: []string{"check"}, out: emptyAdoption + "CHECK:pass|0|0\n"},
		{args: []string{"check", "--strict"}, out: emptyAdoption + "CHECK:pass|0|0\n"},
		{args: []string{"check", "--json"}, out: "{\"status\":\"pass\",\"findings\":[],\"failing\":0,\"summary\":" + emptyAdoptionJSON + "}\n"},
	}
	for _, s := range steps {
		code, out, errs := call(s.args...)
		if code != s.code || errs != "" {
			t.Fatalf("%v: exit %d stderr %q", s.args, code, errs)
		}
		if s.jsonKeys == nil {
			if out != s.out {
				t.Fatalf("%v: stdout %q\nwant %q", s.args, out, s.out)
			}
			continue
		}
		var got map[string]any
		if err := json.Unmarshal([]byte(out), &got); err != nil {
			t.Fatalf("%v: %v", s.args, err)
		}
		for k, v := range s.jsonKeys {
			if !reflect.DeepEqual(got[k], v) {
				t.Fatalf("%v: %s = %#v, want %#v", s.args, k, got[k], v)
			}
		}
		for k := range got {
			if _, old := s.jsonKeys[k]; !old && !jsonAdditions[k] {
				t.Fatalf("%v: unexpected key %q", s.args, k)
			}
		}
	}
	data, err := os.ReadFile(filepath.Join(root, registry.ScannedPath))
	if err != nil || string(data) != characterizedScanned {
		t.Fatalf("_scanned.yaml: %v\n%s", err, data)
	}
	if _, err := os.Stat(filepath.Join(root, registry.RegistryDir, "_scoped.yaml")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("_scoped.yaml must not exist without scoped data: %v", err)
	}
}
