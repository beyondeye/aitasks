// plugin writes an executable scanner plugin printing out.
func plugin(t *testing.T, r *fixture.Repo, name, script string) {
	t.Helper()
	r.Write(t, PluginDir+"/"+name, "#!/bin/sh\n"+script)
	if err := os.Chmod(filepath.Join(r.Dir, PluginDir, name), 0o755); err != nil {
		t.Fatal(err)
	}
}

func TestPluginProtocol(t *testing.T) {
	r := repo(t, map[string]string{"res/a.xml": "<a/>\n", "src/A.kt": "package a\n", "src/B.kt": "package b\n"})
	plugin(t, r, "xml", `grep -q '^res/a.xml$' && echo '{"file":"src/A.kt","deps":["res/a.xml"],"reads":["res/**"]}' && echo '{"file":"res/a.xml","opaque":"generated by aapt"}'`+"\n")
	r.Write(t, PluginDir+"/notes.txt", "not executable\n")
	if err := os.Symlink("xml", filepath.Join(r.Dir, PluginDir, "link")); err != nil {
		t.Fatal(err)
	}
	g := scanRepo(t, r)
	requireEdge(t, g, "src/A.kt", "res/a.xml", "", "plugin:xml")
	if f, _ := g.Facts("src/A.kt"); !slices.Equal(f.Reads, []string{"res/**"}) {
		t.Fatalf("reads %v", f.Reads)
	}
	if got := g.Opaque("res/a.xml"); got != "plugin:xml" {
		t.Fatalf("opaque %q", got)
	}
}

func TestPluginRefusals(t *testing.T) {
	old := PluginTimeout
	PluginTimeout = 300 * time.Millisecond
	t.Cleanup(func() { PluginTimeout = old })
	for name, script := range map[string]string{
		"exit":       "exit 3\n",
		"malformed":  "echo 'not json'\n",
		"unknownkey": `echo '{"file":"src/A.kt","covers":["x"]}'` + "\n",
		"nofile":     `echo '{"deps":["src/A.kt"]}'` + "\n",
		"outside":    `echo '{"file":"src/A.kt","deps":["nope.kt"]}'` + "\n",
		"badpath":    `echo '{"file":"../x","deps":[]}'` + "\n",
		"badglob":    `echo '{"file":"src/A.kt","reads":["["]}'` + "\n",
		"emptyopq":   `echo '{"file":"src/A.kt","opaque":""}'` + "\n",
		"timeout":    "exec sleep 5\n",
		"trailbrack": `echo '{"file":"src/A.kt"}]'` + "\n",
		"trailbrace": `echo '{"file":"src/A.kt"}}'` + "\n",
		"twovalues":  `echo '{"file":"src/A.kt"} {"file":"src/A.kt"}'` + "\n",
	} {
		t.Run(name, func(t *testing.T) {
			r := repo(t, map[string]string{"src/A.kt": "package a\n"})
			plugin(t, r, name, script)
			_, err := Scan(bg, r.Dir, Options{Uncached: true})
			var pe *PluginError
			if !errors.As(err, &pe) || pe.Plugin != name {
				t.Fatalf("err = %v", err)
			}
			l, lerr := pe.Line()
			if lerr != nil || !strings.HasPrefix(l, "SCANNER_ERROR:"+name+"|") || pe.ExitCode() != 3 {
				t.Fatalf("line %q %v", l, lerr)
			}
		})
	}
}

// A timed-out plugin whose shell still has children holding its output pipes
// fails within the timeout plus the drain bound, and the children die with
// it (the whole process group is killed).
func TestPluginTimeoutKillsChildren(t *testing.T) {
	oldT, oldD := PluginTimeout, pluginDrain
	PluginTimeout, pluginDrain = 100*time.Millisecond, 200*time.Millisecond
	t.Cleanup(func() { PluginTimeout, pluginDrain = oldT, oldD })
	pidFile := filepath.Join(t.TempDir(), "pid")
	t.Setenv("PLUGIN_PID_FILE", pidFile)
	r := repo(t, map[string]string{"src/A.kt": "package a\n"})
	// Not `exec sleep`: the shell forks children that inherit stdout.
	plugin(t, r, "slow", "(sleep 30; echo late) &\necho $! > \"$PLUGIN_PID_FILE\"\nsleep 30\necho '{\"file\":\"src/A.kt\"}'\n")
	start := time.Now()
	_, err := Scan(bg, r.Dir, Options{Uncached: true})
	elapsed := time.Since(start)
	var pe *PluginError
	if !errors.As(err, &pe) || !strings.Contains(pe.Reason, "timed out") {
		t.Fatalf("err = %v", err)
	}
	if elapsed > 3*time.Second {
		t.Fatalf("the scan waited %v on pipes held by the plugin's children", elapsed)
	}
	data, err := os.ReadFile(pidFile)
	if err != nil {
		t.Fatal(err)
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(data)))
	if err != nil {
		t.Fatal(err)
	}
	deadline := time.Now().Add(2 * time.Second)
	for syscall.Kill(pid, 0) == nil {
		if time.Now().After(deadline) {
			syscall.Kill(pid, syscall.SIGKILL)
			t.Fatalf("the plugin's child %d outlived the timeout", pid)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

// Output is bounded while the plugin runs: a plugin flooding stdout is
// killed and refused once it passes the limit, and a flood on stderr is
// truncated (only its first line is reported, itself shortened).
func TestPluginOutputIsBounded(t *testing.T) {
	oldOut, oldErr, oldT := pluginOutputMax, pluginStderrMax, PluginTimeout
	pluginOutputMax, pluginStderrMax, PluginTimeout = 1<<20, 4<<10, 10*time.Second
	t.Cleanup(func() { pluginOutputMax, pluginStderrMax, PluginTimeout = oldOut, oldErr, oldT })
	r := repo(t, map[string]string{"src/A.kt": "package a\n"})
	plugin(t, r, "flood", `yes '{"file":"src/A.kt"}'`+"\n")
	start := time.Now()
	_, err := Scan(bg, r.Dir, Options{Uncached: true})
	var pe *PluginError
	if !errors.As(err, &pe) || !strings.Contains(pe.Reason, "output exceeds") {
		t.Fatalf("err = %v", err)
	}
	if time.Since(start) > 5*time.Second {
		t.Fatalf("a flooding plugin ran %v", time.Since(start))
	}

	r = repo(t, map[string]string{"src/A.kt": "package a\n"})
	plugin(t, r, "noisy", "head -c 1000000 /dev/zero | tr '\\0' x >&2\nexit 1\n")
	_, err = Scan(bg, r.Dir, Options{Uncached: true})
	if !errors.As(err, &pe) || len(pe.Reason) > 600 || !strings.Contains(pe.Reason, "xxx") {
		t.Fatalf("stderr flood: %d bytes: %.80q", len(pe.Reason), pe.Reason)
	}
}
